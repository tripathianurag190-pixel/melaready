def password_hash(password, salt=None):
    salt=salt or secrets.token_bytes(16)
    digest=hashlib.pbkdf2_hmac("sha256",password.encode(),salt,600_000)
    return salt.hex()+":"+digest.hex()
def password_ok(password, saved):
    try:
        salt,digest=saved.split(":",1)
        return hmac.compare_digest(password_hash(password,bytes.fromhex(salt)).split(":",1)[1],digest)
    except Exception:return False
def invite_code():
    """Exactly three A-Z letters followed by three digits; randomness is server-side."""
    alphabet = string.ascii_uppercase
    return "".join(secrets.choice(alphabet) for _ in range(3)) + "".join(
        secrets.choice(string.digits) for _ in range(3)
    )

