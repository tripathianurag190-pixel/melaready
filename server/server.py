class PostgreSQLAdapter:
    """Expose execute/executescript/commit methods used by the legacy API."""
    def __init__(self, connection):
        self.connection = connection

    @staticmethod
    def translate(query):
        statement = query.strip()
        if statement.startswith("INSERT OR IGNORE INTO "):
            statement = statement.replace("INSERT OR IGNORE INTO ", "INSERT INTO ", 1) + " ON CONFLICT DO NOTHING"
        elif statement.startswith("INSERT OR REPLACE INTO locations VALUES"):
            statement = statement.replace(
                "INSERT OR REPLACE INTO locations VALUES",
                "INSERT INTO locations(event_id,user_id,lat,lng,accuracy,captured,expires) VALUES", 1
            ) + (" ON CONFLICT(event_id,user_id) DO UPDATE SET "
                 "lat=EXCLUDED.lat,lng=EXCLUDED.lng,accuracy=EXCLUDED.accuracy,"
                 "captured=EXCLUDED.captured,expires=EXCLUDED.expires")
        return statement.replace("?", "%s")

    def execute(self, query, params=()):
        return self.connection.execute(self.translate(query), params)

    def executescript(self, statements):
        for stmt in statements.split(";"):
            if stmt.strip():
                self.connection.execute(stmt.strip())

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def close(self):
        self.connection.close()

@contextmanager
def connect():
    if DATABASE_URL:
        try:
            import psycopg
            from psycopg.rows import dict_row
        except ImportError as exc:
            raise RuntimeError("Install dependencies with pip install -r requirements.txt") from exc
        raw = psycopg.connect(DATABASE_URL, connect_timeout=15, row_factory=dict_row)
        c = PostgreSQLAdapter(raw)
    else:
        c = sqlite3.connect(DB, timeout=10)
        c.row_factory = sqlite3.Row
        c.execute("PRAGMA foreign_keys=ON")
    try:
        yield c
        c.commit()
    except Exception:
        c.rollback()
        raise
    finally:
        c.close()

def init():
    with connect() as c:
        c.executescript(POSTGRES_SCHEMA if DATABASE_URL else SQLITE_SCHEMA)

