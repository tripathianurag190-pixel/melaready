class PostgreSQLAdapter:
    """Expose execute/executescript/commit methods used by the legacy API."""
    def __init__(self, connection):
        self.connection = connection

    @staticmethod
    def translate(query):
        statement = query.strip()
        if statement.startswith("INSERT OR IGNORE INTO "):
            statement = statement.replace("INSERT OR IGNORE INTO ", "INSERT INTO ", 1) + " ON CONFLICT DO NOTHING"
        elif statement.startswith("INSERT OR REPLACE INTO locations VALUES"):
            statement = statement.replace(
                "INSERT OR REPLACE INTO locations VALUES",
                "INSERT INTO locations(event_id,user_id,lat,lng,accuracy,captured,expires) VALUES", 1
            ) + (" ON CONFLICT(event_id,user_id) DO UPDATE SET "
                 "lat=EXCLUDED.lat,lng=EXCLUDED.lng,accuracy=EXCLUDED.accuracy,"
                 "captured=EXCLUDED.captured,expires=EXCLUDED.expires")
        return statement.replace("?", "%s")

    def execute(self, query, params=()):
        return self.connection.execute(self.translate(query), params)

    def executescript(self, statements):
        for stmt in statements.split(";"):
            if stmt.strip():
                self.connection.execute(stmt.strip())

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def close(self):
        self.connection.close()

@contextmanager
def connect():
    if DATABASE_URL:
        try:
            import psycopg
            from psycopg.rows import dict_row
        except ImportError as exc:
            raise RuntimeError("Install dependencies with pip install -r requirements.txt") from exc
        raw = psycopg.connect(DATABASE_URL, connect_timeout=15, row_factory=dict_row)
        c = PostgreSQLAdapter(raw)
    else:
        c = sqlite3.connect(DB, timeout=10)
        c.row_factory = sqlite3.Row
        c.execute("PRAGMA foreign_keys=ON")
    try:
        yield c
        c.commit()
    except Exception:
        c.rollback()
        raise
    finally:
        c.close()

def init():
    """Additive migration: preserves existing users, event codes, voice clips and tasks."""
    with connect() as c:
        c.executescript(POSTGRES_SCHEMA if DATABASE_URL else SQLITE_SCHEMA)
        migrations = {
            "events": {"locked": "INTEGER NOT NULL DEFAULT 0", "archived": "INTEGER NOT NULL DEFAULT 0", "updated": "BIGINT NOT NULL DEFAULT 0"},
            "audit": {"target": "TEXT NOT NULL DEFAULT ''", "detail": "TEXT NOT NULL DEFAULT ''"},
            "reports": {"reporter": "TEXT NOT NULL DEFAULT ''"},
        }
        for table, fields in migrations.items():
            if DATABASE_URL:
                for name, decl in fields.items():
                    c.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {name} {decl}")
            else:
                existing={row["name"] for row in c.execute(f"PRAGMA table_info({table})").fetchall()}
                for name, decl in fields.items():
                    if name not in existing:
                        c.execute(f"ALTER TABLE {table} ADD COLUMN {name} {decl}")

def is_owner(c,event,user_id):
    row=c.execute("SELECT lead_id FROM events WHERE id=?",(event,)).fetchone()
    return bool(row and row["lead_id"]==user_id)

def owner_only(c,event,user_id):
    member(c,event,user_id)
    if not is_owner(c,event,user_id):
        raise ApiError(403,"Only the event creator can change event settings, assignments or moderation")

def event_open(c,event):
    row=c.execute("SELECT archived FROM events WHERE id=?",(event,)).fetchone()
    if not row: raise ApiError(404,"Event not found")
    if row["archived"]: raise ApiError(409,"Event is archived and read-only")

def audit(c,event,user,action,target='',detail=''):
    """Server timestamp and authenticated actor; don't log passwords, audio or coordinates."""
    c.execute("INSERT INTO audit(event_id,actor,action,created,target,detail) VALUES(?,?,?,?,?,?)",
              (event,user,action,now(),str(target or '')[:80],str(detail or '')[:240]))

