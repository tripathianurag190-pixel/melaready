# In-process pilot protection against guessing short invite codes. A production
# deployment should use persistent/distributed rate limits as well.
_JOIN_FAILURES = defaultdict(deque)
_JOIN_LOCK = Lock()
def join_attempt(user_id, failed=False, successful=False):
    with _JOIN_LOCK:
        events=_JOIN_FAILURES[user_id]
        cutoff=now()-300
        while events and events[0]<cutoff: events.popleft()
        if successful:
            events.clear()
        elif failed:
            events.append(now())
        elif len(events)>=8:
            raise ApiError(429,"Too many incorrect invite codes. Try again later.")

